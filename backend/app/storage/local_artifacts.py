from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

import joblib
import pandas as pd

from app.core.config import settings
from app.utils.serialization import json_safe


class LocalArtifactStore:
    """Stores app-generated artifacts below a single configured root directory.

    Never load a joblib/pickle file supplied by a client. These internal files are
    generated by this application and should remain outside the web root.
    """

    def __init__(self) -> None:
        self.root = settings.artifact_root
        self.root.mkdir(parents=True, exist_ok=True)

    def dataset_dir(self, dataset_id: str) -> Path:
        path = (self.root / dataset_id).resolve()
        if self.root not in path.parents:
            raise ValueError("Invalid dataset path")
        path.mkdir(parents=True, exist_ok=True)
        return path

    def path(self, dataset_id: str, filename: str) -> Path:
        if Path(filename).name != filename or filename in {".", ".."}:
            raise ValueError("Invalid artifact filename")
        return self.dataset_dir(dataset_id) / filename

    def save_bytes(self, dataset_id: str, filename: str, content: bytes) -> Path:
        path = self.path(dataset_id, filename)
        path.write_bytes(content)
        return path

    def save_dataframe(self, dataset_id: str, filename: str, df: pd.DataFrame) -> Path:
        path = self.path(dataset_id, filename)
        df.to_pickle(path)
        return path

    def load_dataframe(self, path: str) -> pd.DataFrame:
        artifact = Path(path).resolve()
        if self.root not in artifact.parents or not artifact.is_file():
            raise FileNotFoundError("The temporary dataset artifact is no longer available.")
        # This file was generated by the application, never directly accepted from a user.
        value = pd.read_pickle(artifact)
        if not isinstance(value, pd.DataFrame):
            raise ValueError("Stored data artifact is invalid")
        return value

    def save_json(self, dataset_id: str, filename: str, value: Any) -> Path:
        path = self.path(dataset_id, filename)
        path.write_text(json.dumps(json_safe(value), ensure_ascii=False, indent=2), encoding="utf-8")
        return path

    def load_json(self, path: str) -> dict:
        artifact = Path(path).resolve()
        if self.root not in artifact.parents or not artifact.is_file():
            raise FileNotFoundError("The temporary analysis artifact is no longer available.")
        return json.loads(artifact.read_text(encoding="utf-8"))

    def save_model(self, dataset_id: str, filename: str, model: Any) -> Path:
        path = self.path(dataset_id, filename)
        joblib.dump(model, path)
        return path

    def remove_dataset(self, dataset_id: str) -> None:
        path = (self.root / dataset_id).resolve()
        if self.root in path.parents and path.exists():
            shutil.rmtree(path, ignore_errors=True)


artifact_store = LocalArtifactStore()
